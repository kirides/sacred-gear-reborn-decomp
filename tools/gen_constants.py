#!/usr/bin/env python3
"""Writes the constant tables the mod's patches refer to (mods/reborn/constants/*.lua), from the game's own data:

  python tools/gen_constants.py --gog "<game folder>" --out mods/reborn/constants

  creature.lua  CREATURE.<NAME> = object type id, for every creature type (kind 3) that has a name;
  item.lua      ITEM.<NAME> = object type id of the items named in sets.bin (the sets of the game);
  opcode.lua    OPCODE.<NAME> = script opcode, the instructions the patches use.

Where the names come from: data/object_types.tsv lists the game's object types (id, kind, model file name, German display name; dumped from the running
game by Sacred Gear: `gear.data.object_types` and `gear.text.get`). The English name is the text of `scripts/us/global.res` that has the same key as the
German text in `scripts/de/global.res` (when several keys have that German text and their English texts differ the first by key is used and the table
says so in a comment). NAME is the English name in capitals; the same name for several ids gets `_2`, `_3` ... in id order.
"""
import argparse
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import restext

HERE = os.path.dirname(os.path.abspath(__file__))
START_WORD, START_ROWS = 361, 64          # balance.bin: the starting items of the heroes, 8 rows of 8 words (see make_patches.py)
OPCODES = [('CREATE_OBJ', 8), ('FILL_SECTOR', 51), ('SET_VAR', 67)]


def load_types(path):
    rows = []
    for line in open(path, encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        i, kind, model, name = line.rstrip('\n').split('\t')
        rows.append((int(i), int(kind), model, name))
    return rows


def ident(text):
    s = re.sub(r'[^A-Za-z0-9]+', '_', text.strip()).strip('_').upper()
    return ('_' + s) if s and s[0].isdigit() else s


def norm(s):
    return re.sub(r'[^A-Za-z0-9]', '', s)


def english_names(gog):
    tx = lambda t, k: t[k][0][1].decode('utf-16le').strip()
    de = restext.parse(open(os.path.join(gog, 'scripts', 'de', 'global.res'), 'rb').read())
    us = restext.parse(open(os.path.join(gog, 'scripts', 'us', 'global.res'), 'rb').read())
    by = collections.defaultdict(list)
    for key in sorted(de):
        if key in us:
            by[norm(tx(de, key))].append(tx(us, key))
    return by


def table(rows, by):
    """[(NAME, id, comment)] for the rows, names made unique."""
    out, seen = [], collections.Counter()
    for i, kind, model, german in sorted(rows):
        english = by.get(norm(german), [])
        distinct = sorted(set(e for e in english if e))
        text = (english[0] if english else '') or german
        note = ''
        if len(distinct) > 1:
            note = 'also: ' + ', '.join(e for e in distinct if e != text)
        elif not english:
            note = 'no English text found: German "%s"' % german
        base = ident(text) or ident(os.path.splitext(model)[0]) or 'TYPE_%d' % i
        seen[base] += 1
        name = base if seen[base] == 1 else '%s_%d' % (base, seen[base])
        out.append((name, i, note))
    return out


def lua_constants(title, global_name, entries):
    lines = ['-- %s' % title, '-- Generated by tools/gen_constants.py from the game\'s own data (see its docstring); do not edit.',
             'return {']
    width = max(len(n) for n, _, _ in entries)
    for name, i, note in entries:
        lines.append('    %s = %d,%s' % (name.ljust(width), i, ('   -- ' + note) if note else ''))
    lines += ['}', '']
    return '\n'.join(lines)


def lua_meta(tables):
    """LuaLS annotations for the constants (the patch files use the globals CREATURE, ITEM, OPCODE)."""
    lines = ['---@meta', '-- Generated by tools/gen_constants.py: names of the constants for the editor (LuaLS); Gear defines the real tables when it reads a patch.', '']
    for glob, entries in tables:
        lines.append('---@class %sConstants' % glob.capitalize())
        for name, i, _ in entries:
            lines.append('---@field %s integer %d' % (name, i))
        lines += ['', '---@type %sConstants' % glob.capitalize(), '%s = nil' % glob, '']
    return chr(10).join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--gog', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--balance', action='append', default=[], help="a balance.bin (the game's, ReBorn's): the starting items in it are ITEM names too")
    ap.add_argument('--types', default=os.path.join(os.path.dirname(HERE), 'data', 'object_types.tsv'))
    a = ap.parse_args()
    rows = load_types(a.types)
    by = english_names(a.gog)
    os.makedirs(a.out, exist_ok=True)
    creatures = table([r for r in rows if r[1] == 3], by)
    open(os.path.join(a.out, 'creature.lua'), 'w', encoding='utf8', newline='\n').write(
        lua_constants('CREATURE: object type ids of the creatures (monsters, heroes, townspeople).', 'CREATURE', creatures))
    # items: the types named in sets.bin
    import struct
    sets = open(os.path.join(a.gog, 'bin', 'sets.bin'), 'rb').read()
    used = set()
    for r in range(struct.unpack_from('<I', sets, 0)[0]):
        used.update(w for w in struct.unpack_from('<10I', sets, 4 + r * 112) if w)
    for path in a.balance + [os.path.join(a.gog, 'bin', 'balance.bin')]:
        data = open(path, 'rb').read()
        used.update(w for w in struct.unpack_from('<%dI' % START_ROWS, data, START_WORD * 4) if w)
    items = table([r for r in rows if r[0] in used], by)
    open(os.path.join(a.out, 'item.lua'), 'w', encoding='utf8', newline='\n').write(
        lua_constants('ITEM: object type ids of items: the sets of the game (sets.bin) and the starting items of the heroes (balance.bin).', 'ITEM', items))
    open(os.path.join(a.out, 'opcode.lua'), 'w', encoding='utf8', newline='\n').write(
        lua_constants('OPCODE: script instruction opcodes the patches use (docs/file-formats.md).', 'OPCODE', [(n, v, '') for n, v in OPCODES]))
    opcodes = [(n, v, '') for n, v in OPCODES]
    os.makedirs(os.path.join(os.path.dirname(a.out), 'meta'), exist_ok=True)
    open(os.path.join(os.path.dirname(a.out), 'meta', 'constants.lua'), 'w', encoding='utf8', newline=chr(10)).write(
        lua_meta([('CREATURE', creatures), ('ITEM', items), ('OPCODE', opcodes)]))
    print('%d creatures, %d set items, %d opcodes' % (len(creatures), len(items), len(OPCODES)))


if __name__ == '__main__':
    main()
