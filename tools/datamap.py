# The data side of the port: which game path each ReBorn data file is opened as (derived from the changed path strings
# in ReBorn's exe, not written by hand), the manifest of new or changed files, and the mod's overlay.txt.
import hashlib, os, re, shutil

SKIP_DIRS = {'_backup', '_reborn-test', 'gearautomation', 'capture', 'logs-before', 'save', 'sacredbild', 'mods'}
SKIP_EXT = {'.log', '.dmp', '.pdb', '.lnk', '.pdf', '.dll', '.exe', '.ico', '.ini', '.cfg', '.txt', '.html', '.rtf',
            '.dat', '.msg', '.script', '.info', '.hashdb', '.jpg', '.zip', '.json'}


def sha(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for c in iter(lambda: f.read(1 << 20), b''):
            h.update(c)
    return h.hexdigest()


def _cstr(img, a):
    s = a
    while s > img.base and img.rd(s - 1, 1)[0] != 0 and a - s < 80:
        s -= 1
    e = a
    while img.rd(e, 1)[0] != 0 and e - a < 120:
        e += 1
    return img.rd(s, e - s).decode('latin1')


def derive_renames(patches, de, rb):
    """({vanilla basename (lower): ReBorn basename (lower)}, {vanilla directory: ReBorn directory}) from the path strings
    ReBorn's exe changes: 'ITEMS.PAK' -> 'SRitm.pak', 'global.res' -> 'SRglbl.res', and the directory `bin` -> `SRB`."""
    files, dirs = {}, {}
    token = re.compile(r'[A-Za-z0-9_.%\\]+')
    bin_to_srb = 0
    for p in patches:
        if p['class'] == 'table' and p['old'] in (b'bin', b'Bin') and p['new'] == b'SRB':
            bin_to_srb += 1
        if p['class'] != 'string':
            continue
        a = _cstr(de, p['de']), _cstr(rb, p['de'])
        ta, tb = token.findall(a[0]), token.findall(a[1])
        if len(ta) != len(tb):
            continue
        for x, y in zip(ta, tb):
            if x != y and '.' in x and '.' in y and x.lower().rsplit('.', 1)[-1] in ('pak', 'res', 'bin'):
                files[os.path.basename(x.replace('\\', '/')).lower()] = os.path.basename(y.replace('\\', '/')).lower()
    if bin_to_srb >= 3:
        dirs['bin'] = 'srb'
    return files, dirs


def game_path(rel, renames):
    """The path the game opens a ReBorn file as (lower case, forward slashes): the inverse of the renames."""
    files, dirs = renames
    inv_files = {v: k for k, v in files.items()}
    inv_dirs = {v: k for k, v in dirs.items()}
    parts = rel.lower().split('/')
    if parts[0] in inv_dirs:
        parts[0] = inv_dirs[parts[0]]
    if parts[-1] in inv_files:
        parts[-1] = inv_files[parts[-1]]
    return '/'.join(parts)


def build_manifest(reborn, vanilla, renames):
    """New or changed data files of the ReBorn folder against the vanilla install, with the game path each is opened as."""
    files = []
    for root, dirs, fs in os.walk(reborn):
        dirs[:] = [d for d in dirs if d.lower() not in SKIP_DIRS and not d.lower().startswith('_')]
        for name in fs:
            if os.path.splitext(name)[1].lower() in SKIP_EXT:
                continue
            path = os.path.join(root, name)
            rel = os.path.relpath(path, reborn).replace('\\', '/')
            game = game_path(rel, renames)
            vpath = os.path.join(vanilla, *game.split('/'))
            size = os.path.getsize(path)
            if os.path.exists(vpath) and os.path.getsize(vpath) == size and sha(vpath) == sha(path):
                continue
            files.append({'path': rel, 'game': game, 'size': size, 'sha256': sha(path),
                          'status': 'new' if not os.path.exists(vpath) else 'changed'})
    # a path ReBorn serves under a renamed file wins over a copy of the original (global.res next to SRglbl.res)
    renamed = {f['game'] for f in files if f['path'].lower() != f['game']}
    files = [f for f in files if f['path'].lower() != f['game'] or f['game'] not in renamed]
    files.sort(key=lambda f: f['path'].lower())
    return {'reborn': os.path.basename(reborn), 'renames': {'files': renames[0], 'dirs': renames[1]}, 'files': files}


def write_overlay(mod_dir, reborn, manifest, mode, link=True):
    """mods/reborn/overlay.txt (+ data/ with hard links or copies). mode: 'none', 'bin' (the SRB data and the text) or 'all'."""
    lines = ['# Generated by tools/reborn_port.py from the ReBorn folder: the game path = the mod file.',
             '# Sacred ReBorn by the Sacred ReBorn Overlookers group.']
    chosen = []
    for f in manifest['files']:
        game = f['game']
        if mode == 'none':
            continue
        if mode == 'bin' and not (game.startswith('bin/') or game.startswith('scripts/')):
            continue
        chosen.append(f)
        lines.append(f"{game.replace('/', chr(92))} = data\\{f['path'].replace('/', chr(92))}")
    os.makedirs(mod_dir, exist_ok=True)
    with open(os.path.join(mod_dir, 'overlay.txt'), 'w', newline='\n') as out:
        out.write('\n'.join(lines) + '\n')
    for f in chosen:
        src = os.path.join(reborn, *f['path'].split('/'))
        dst = os.path.join(mod_dir, 'data', *f['path'].split('/'))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if os.path.exists(dst):
            os.remove(dst)
        try:
            if not link:
                raise OSError
            os.link(src, dst)
        except OSError:
            shutil.copy2(src, dst)
    return len(chosen)
