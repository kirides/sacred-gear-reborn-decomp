def balance_split(original, mine):
    """({section index: {row: {field: word}}}, the other changed word runs): named tables as record edits, the rest stays word runs."""
    import struct
    edits = {}
    rest = bytearray(mine)
    for si, sec in enumerate(BALANCE_SECTIONS):
        for row in range(sec['rows']):
            for k, field in enumerate(sec['fields']):
                w = sec['first'] + row * sec['words'] + k
                new, old = struct.unpack_from('<I', mine, w * 4)[0], struct.unpack_from('<I', original, w * 4)[0]
                if new != old:
                    edits.setdefault(si, {}).setdefault(row, {})[field] = new
                    struct.pack_into('<I', rest, w * 4, old)
    return edits, word_runs(bytes(rest), original)


def apply_balance(original, edits, runs):
    import struct
    out = bytearray(apply_words(original, runs))
    for si, rows in edits.items():
        sec = BALANCE_SECTIONS[si]
        for row, fields in rows.items():
            for field, v in fields.items():
                struct.pack_into('<I', out, (sec['first'] + row * sec['words'] + sec['fields'].index(field)) * 4, v)
    return bytes(out)


def lua_balance_patch(target, original, edits, runs, note, constants):
    items = {v: k for k, v in constants.get('ITEM', {}).items()}

    def key(sec, row):
        names = {v: k for k, v in constants.get(sec.get('key', ''), {}).items()}
        return '%s.%s' % (sec['key'], names[row]) if row in names else str(row)

    def value(sec, v):
        if sec['kind'] == 'float':
            return word_literal(v)
        return ('ITEM.%s' % items[v]) if sec['kind'] == 'item' and v in items else str(v)
    lines = ['-- %s' % note,
             "-- Generated by tools/make_patches.py: the words that differ from the game's own file. balance.bin: a count word (the size of the global block),",
             '-- then the global block, copied to memory at 0xAD4490 (Sacred.exe 0x711F64), then more tables. Word i is the bytes 4 * i .. 4 * i + 3 of the file.',
             '-- `sections`: tables with named fields (one record per hero class or region; a difficulty table has one record with a field per difficulty);',
             '-- `ops`: words that are not named, {first word, {values}} with their place in memory.',
             'return {',
             "    kind = 'words',",
             "    target = '%s'," % target.replace(chr(92), '/'),
             '    size = %d,' % len(original),
             '    crc32 = 0x%08x,' % (zlib.crc32(original) & 0xFFFFFFFF),
             '    sections = {']
    for si in sorted(edits):
        sec = BALANCE_SECTIONS[si]
        fields = ', '.join('%s = %d' % (f, k) for k, f in enumerate(sec['fields']))
        lines += ['        {   -- %s' % sec['title'],
                  '            records = {first = %d, words = %d, fields = {%s}},' % (sec['first'], sec['words'], fields),
                  '            edits = {']
        for row in sorted(edits[si]):
            body = ', '.join('%s = %s' % (f, value(sec, v)) for f, v in edits[si][row].items())
            lines.append('                {record = %s, %s},' % (key(sec, row), body))
        lines += ['            },', '        },']
    lines += ['    },', '    ops = {']
    note_for = balance_note(original)
    for first, values in runs:
        lines.append('        {%d, {%s}},   -- %s' % (first, ', '.join(word_literal(v) for v in values), note_for(first, len(values))))
    lines += ['    },', '}', '']
    return chr(10).join(lines)


def lua_text_patch(target, original, set_, remove, note):
    old = restext.parse(original)
    lines = ['-- %s' % note,
             "-- Generated by tools/make_patches.py: the texts that are new or differ from the game's own table, by text id.",
             'return {',
             "    kind = 'texts',",
             "    target = '%s'," % target.replace(chr(92), '/'),
             '    size = %d,' % len(original),
             '    crc32 = 0x%08x,' % (zlib.crc32(original) & 0xFFFFFFFF)]
    lines += restext.lua_table(set_, remove, old)
    lines += ['}', '']
    return '\n'.join(lines)


BS = chr(92)
USE_CASES = [
    (re.compile('^bin' + re.escape(BS) + 'balance[.]bin$'), 'balance', 'Balance tables (balance.bin).'),
    (re.compile('^bin' + re.escape(BS) + 'sets[.]bin$'), 'sets', 'Item sets (sets.bin).'),
    (re.compile('^scripts' + re.escape(BS) + '(.+)' + re.escape(BS) + 'global[.]res$'), 'texts', 'Texts of the language %s (global.res).'),
]


SCRIPT_RX = re.compile('^bin' + re.escape(BS) + '(.+)' + re.escape(BS) + '(funkcode|startcode)[.]bin$')
DEFPOS_RX = re.compile('^bin' + re.escape(BS) + '(.+)' + re.escape(BS) + 'defpos[.]bin$')


def patch_path(game):
    g = game.lower()
    for rx, folder, note in USE_CASES:
        m = rx.match(g)
        if not m:
            continue
        if folder in ('balance', 'sets'):
            return 'patches/%s.lua' % folder, note
        if folder == 'texts':
            return 'patches/texts/%s.lua' % m.group(1), note % m.group(1)
        variant = m.group(1).replace(BS, '_')
        kind = os.path.basename(g.replace(BS, '/')).replace('.bin', '')
        return 'patches/%s/%s/%s.lua' % (folder, variant, kind), note % m.group(1).replace(BS, '/')
    return None, None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--full', required=True, help='the generated mod folder with the full data files (overlay.txt, data/)')
    ap.add_argument('--gog', required=True, help="the game folder whose files are the baseline")
    ap.add_argument('--extra', action='append', default=[], help="more folders with the game's own files (same layout, e.g. scripts/fr/global.res of "
                    "a French install): used for files --gog does not have; the game folder must hold the same file when the mod runs")
    ap.add_argument('--out', required=True, help='mods/reborn')
    a = ap.parse_args()
    rules, saves = read_rules(os.path.join(a.full, 'overlay.txt'))
    out_rules, kept, dropped = [], [], []
    scripts, script_rules, derived = {}, [], []
    converted = runs = replaced_bytes = patch_bytes = 0
    shutil.rmtree(os.path.join(a.out, 'patches'), ignore_errors=True)
    os.makedirs(os.path.join(a.out, 'patches'), exist_ok=True)
    for game, value in rules:
        src = os.path.join(a.full, value.replace(BS, os.sep))
        base = os.path.join(a.gog, game.replace(BS, os.sep))
        for extra in a.extra:
            if not os.path.exists(base):
                base = os.path.join(extra, game.replace(BS, os.sep))
        rel_patch, note = patch_path(game)
        if DEFPOS_RX.match(game.lower()) and os.path.exists(src) and os.path.exists(base):
            # DefPos.bin is derived data: the game makes its own layout from the plain file (see defpos.py). Nothing to ship if ReBorn's file holds
            # the same positions as the game's; if a ReBorn release moves a position this stops and a positions patch has to be written.
            if not defpos.same_positions(open(src, 'rb').read(), open(base, 'rb').read()):
                raise SystemExit('%s: ReBorn has other positions than the game: DefPos.bin needs a readable positions patch (see tools/defpos.py)' % game)
            derived.append(game)
            continue
        sm = SCRIPT_RX.match(game.lower())
        if sm and os.path.exists(src) and os.path.exists(base):
            mine = open(src, 'rb').read()
            orig = open(base, 'rb').read()
            if mine == orig:
                continue
            if len(mine) != len(orig):
                raise SystemExit('%s: ReBorn changes the size of a script file: not an in-place edit' % game)
            funk = sm.group(2) == 'funkcode'
            if funk:
                vec = open(os.path.join(os.path.dirname(base), 'Vectoren.bin'), 'rb').read()
                edits = script_edits.edits_funk(orig, mine, vec)
                assert script_edits.apply_funk(orig, vec, edits) == mine, 'the script edits for %s do not rebuild the file' % game
            else:
                edits = script_edits.edits_start(orig, mine)
                assert script_edits.apply_start(orig, edits) == mine, 'the script edits for %s do not rebuild the file' % game
            scripts[game.replace(BS, '/')[4:]] = (funk, edits)
            script_rules.append(game)
            continue
        if rel_patch and os.path.exists(src):
            if not os.path.exists(base):
                dropped.append(game)
                continue
            mine = open(src, 'rb').read()
            orig = open(base, 'rb').read()
            if rel_patch.startswith('patches/texts/'):
                # a text table: the texts that are new or differ, by id (readable), not byte runs
                set_, remove = restext.delta(mine, orig)
                assert restext.apply(orig, set_, remove) == mine, 'the text patch for %s does not rebuild the file' % game
                ops = [None] * (len(set_) + len(remove))
                text = lua_text_patch(game, orig, set_, remove, note)
            elif rel_patch in ('patches/balance.lua', 'patches/sets.lua') and len(mine) == len(orig) and len(mine) % 4 == 0:
                # tables of 32 bit words: the changed words, numbers (floats where they print exactly)
                ops = word_runs(mine, orig)
                assert apply_words(orig, ops) == mine, 'the word patch for %s does not rebuild the file' % game
                if rel_patch.endswith('sets.lua'):
                    edits = set_edits(orig, mine)
                    assert apply_set_edits(orig, edits) == mine, 'the set patch for %s does not rebuild the file' % game
                    text = lua_set_patch(game, orig, edits, note)
                    ops = edits
                else:
                    named, rest = balance_split(orig, mine)
                    assert apply_balance(orig, named, rest) == mine, 'the balance patch for %s does not rebuild the file' % game
                    text = lua_balance_patch(game, orig, named, rest, note, script_edits.load_constants(os.path.join(a.out, 'constants')))
                    ops = [None] * (sum(len(f) for r in named.values() for f in r.values()) + len(rest))
            else:
                ops = diff_runs(mine, orig) if len(mine) == len(orig) else delta_ops(mine, orig)
                assert apply_ops(orig, ops) == mine, 'the patch for %s does not rebuild the file' % game
                text = None
            if not ops:
                continue                              # identical to the game's file: no rule at all
            dest = os.path.join(a.out, rel_patch.replace('/', os.sep))
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            if text is None:
                text = lua_patch(game, orig, ops, note)
            with open(dest, 'w', encoding='utf8', newline='\n') as f:
                f.write(text)
            out_rules.append((game, 'patch:' + rel_patch.replace('/', BS)))
            converted += 1
            runs += len(ops)
            replaced_bytes += len(mine)
            patch_bytes += len(text)
            continue
        out_rules.append((game, value))
        kept.append((game, value))
