#!/usr/bin/env python3
"""Turns the full data files of a generated ReBorn mod into delta patches against the game's own files.

  python tools/reborn_port.py ... --mod out-test/fullmod --data bin --copy        (the full data files)
  python tools/make_patches.py --full out-test/fullmod --gog "<game folder>" --out mods/reborn

For every rule `game path = data file` of the full mod's overlay.txt whose game file exists in --gog, a Lua data file `patches/...lua` with only
what differs is written and the rule becomes `game path = patch:patches/...lua`: Gear applies the patch to the game's file the first time the
game opens it and serves the result (gear/overlay.cpp). Files of the same size are compared byte by byte (runs of changed bytes); files of
another size by matching stretches (insertions, deletions, replacements). Rules for a game file that does not exist in --gog are dropped (the
game never opens it, and there is nothing to be a baseline); other rules keep their data file and are listed at the end. Every patch is applied
again in memory and compared with the full file before it is written.

Patch file format (pure Lua data):
  return {
    target = 'bin/balance.bin',      -- the game file the patch is for
    size = 24328, crc32 = 0x...,     -- of that file: a patch is only applied to exactly this file
    ops = { {offset, 'hex'}, {offset, 'hex', replaced}, ... }
        -- ascending offsets in the original: the hex bytes replace `replaced` bytes there (default: as many as the hex has)
  }
"""
import argparse
import bisect
import os
import re
import shutil
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import restext
import defpos
import script_edits


def read_rules(path):
    rules = []
    saves = None
    for line in open(path, encoding='utf8'):
        body = line.rstrip('\n').split('#', 1)[0].strip()
        if not body or '=' not in body:
            continue
        key, value = [x.strip() for x in body.split('=', 1)]
        if key.lower() == 'saves':
            saves = value
        else:
            rules.append((key, value))
    return rules, saves


def diff_runs(new, old):
    """[(offset, new bytes)] where `new` differs from `old`, equal length."""
    out, i, n = [], 0, len(new)
    while i < n:
        if new[i] != old[i]:
            j = i
            while j < n and new[j] != old[j]:
                j += 1
            out.append((i, new[i:j]))
            i = j
        else:
            i += 1
    return out


def delta_ops(new, old, k=24, step=8):
    """[(offset in old, replacement bytes, replaced length)], ascending, turning `old` into `new` when the sizes differ: stretches of k or more
    equal bytes are found with an index of `old` taken every `step` bytes; what lies between them is replaced."""
    index = {}
    for i in range(0, len(old) - k + 1, step):
        index.setdefault(old[i:i + k], []).append(i)
    ops, j, cur, start = [], 0, 0, 0
    n = len(new)
    while j <= n - k:
        cand = index.get(new[j:j + k])
        p = None
        if cand:
            at = bisect.bisect_left(cand, cur)
            if at < len(cand):
                p = cand[at]
        if p is None:
            j += 1
            continue
        a, b = j, p                                  # extend the match backwards ...
        while a > start and b > cur and new[a - 1] == old[b - 1]:
            a -= 1
            b -= 1
        e, f = j + k, p + k                          # ... and forwards
        while e < n and f < len(old) and new[e] == old[f]:
            e += 1
            f += 1
        if a > start or b > cur:
            ops.append((cur, new[start:a], b - cur))
        cur, start, j = f, e, e
    if start < n or cur < len(old):
        ops.append((cur, new[start:], len(old) - cur))
    return ops


def apply_ops(old, ops):
    out, at = bytearray(), 0
    for item in ops:
        off, data = item[0], item[1]
        replaced = item[2] if len(item) > 2 else len(data)
        assert off >= at
        out += old[at:off]
        out += data
        at = off + replaced
    out += old[at:]
    return bytes(out)


def lua_patch(target, original, ops, note):
    lines = ['-- %s' % note,
             "-- Generated by tools/make_patches.py: only what differs from the game's own file; Gear applies it when the game opens the file.",
             'return {',
             "    target = '%s'," % target.replace('\\', '/'),
             '    size = %d,' % len(original),
             '    crc32 = 0x%08x,' % (zlib.crc32(original) & 0xFFFFFFFF),
             '    ops = {']
    for item in ops:
        off, data = item[0], item[1]
        if len(item) > 2 and item[2] != len(data):
            lines.append("        {%d, '%s', %d}," % (off, data.hex(), item[2]))
        else:
            lines.append("        {%d, '%s'}," % (off, data.hex()))
    lines += ['    },', '}', '']
    return '\n'.join(lines)


def word_runs(new, old):
    """[(first word index, [values])] where the 32 bit words of `new` differ from `old` (equal sizes, multiples of 4)."""
    import struct
    runs, i, n = [], 0, len(new) // 4
    while i < n:
        if new[i * 4:i * 4 + 4] != old[i * 4:i * 4 + 4]:
            j = i
            values = []
            while j < n and new[j * 4:j * 4 + 4] != old[j * 4:j * 4 + 4]:
                values.append(struct.unpack_from('<I', new, j * 4)[0])
                j += 1
            runs.append((i, values))
            i = j
        else:
            i += 1
    return runs


def word_literal(word):
    """A word as Lua source: an integer, or {f = x} when it is a float that prints exactly (3e-5 .. 3e7)."""
    import struct
    if 0x38000000 <= (word & 0x7FFFFFFF) <= 0x4C000000:
        f = struct.unpack('<f', struct.pack('<I', word))[0]
        short = float('%.7g' % f)
        if struct.pack('<f', short) == struct.pack('<I', word):
            return '{f = %s}' % ('%.7g' % f)
    return str(word)


def lua_word_patch(target, original, runs, note, comments=(), annotate=None):
    lines = ['-- %s' % note,
             "-- Generated by tools/make_patches.py: the 32 bit words that differ from the game's own file (a number, or {f = x} for a float).",
             "-- ops = {{first word index, {values}}, ...}; word i is the bytes 4 * i .. 4 * i + 3 of the file."]
    lines += ['-- ' + c for c in comments]
    lines += ['return {',
              "    kind = 'words',",
              "    target = '%s'," % target.replace(chr(92), '/'),
              '    size = %d,' % len(original),
              '    crc32 = 0x%08x,' % (zlib.crc32(original) & 0xFFFFFFFF),
              '    ops = {']
    for first, values in runs:
        text = '        {%d, {%s}},' % (first, ', '.join(word_literal(v) for v in values))
        if annotate:
            text += '   -- ' + annotate(first, len(values))
        lines.append(text)
    lines += ['    },', '}', '']
    return '\n'.join(lines)


def apply_words(old, runs):
    import struct
    out = bytearray(old)
    for first, values in runs:
        for k, v in enumerate(values):
            struct.pack_into('<I', out, (first + k) * 4, v)
    return bytes(out)


BALANCE_BASE = 0xAD4490      # where the game copies the global block of balance.bin (Sacred.exe 0x711F64 / 0x5F3720)
BALANCE_DIFFICULTY = 0xAD4BA0   # six floats read by 0x56AA10: the factor for difficulty 1..4 and the rest (index (difficulty != 1) & 5, 2 -> 1, 3 -> 2, 4 -> 3)


def balance_note(original):
    """A function word index, count -> text: where the words are in the game's memory and what is known about them."""
    import struct
    block = struct.unpack_from('<I', original, 0)[0]

    def note(first, n):
        off = first * 4 - 4
        text = 'block +0x%X (word %d)' % (off, first)
        if off < block:
            addr = BALANCE_BASE + off
            text += ', memory 0x%X' % addr
            if addr < BALANCE_DIFFICULTY + 24 and addr + 4 * n > BALANCE_DIFFICULTY:
                text += ': includes difficulty factors (see above)'
            else:
                text += ': not named yet'
        else:
            text += ': a table after the global block, not named yet'
        return text
    return note


SET_FIELDS = ['item_%d' % (i + 1) for i in range(10)] + ['set_identifier', 'count_and_index'] + ['word_%d' % i for i in range(12, 28)]


def set_edits(original, mine):
    """[(first record, last record, field name, value)] that turn the sets table `original` into `mine` (28 words per record after a count word)."""
    import struct
    per = {}
    for first, values in word_runs(mine, original):
        for k, v in enumerate(values):
            w = first + k
            if w < 1:
                raise SystemExit('sets.bin: the count word changes')
            per.setdefault((SET_FIELDS[(w - 1) % 28], v), []).append((w - 1) // 28)
    out = []
    for (field, v), recs in sorted(per.items(), key=lambda kv: (kv[1][0], kv[0][0])):
        recs.sort()
        start = prev = recs[0]
        for r in recs[1:] + [None]:
            if r is None or r != prev + 1:
                out.append((start, prev, field, v))
                if r is not None:
                    start = r
            if r is not None:
                prev = r
    return out


def apply_set_edits(original, edits):
    import struct
    out = bytearray(original)
    for a, b, field, v in edits:
        for r in range(a, b + 1):
            struct.pack_into('<I', out, (1 + r * 28 + SET_FIELDS.index(field)) * 4, v)
    return bytes(out)


def lua_set_patch(target, original, edits, note):
    lines = ['-- %s' % note,
             "-- Generated by tools/make_patches.py: the fields that differ from the game's own file. sets.bin: a count word, then 66 records of 28 words",
             '-- (112 bytes): ten item type ids, `set_identifier`, `count_and_index` (the item count in the low byte, the index of the set above it), then words',
             '-- that are not named. The file of the game holds 0x9821F1CE + n in `set_identifier` of set n (a counter, not read by the item code of 0x42C3E0);',
             '-- ReBorn writes 0. Record 0 is a placeholder (0xCCCCCCCC in every word).',
             'return {',
             "    kind = 'words',",
             "    target = '%s'," % target.replace(chr(92), '/'),
             '    size = %d,' % len(original),
             '    crc32 = 0x%08x,' % (zlib.crc32(original) & 0xFFFFFFFF),
             '    records = {first = 1, words = 28, fields = {']
    for i in range(0, 28, 4):
        lines.append('        ' + ' '.join('%s = %d,' % (SET_FIELDS[j], j) for j in range(i, min(i + 4, 28))))
    lines += ['    }},', '    edits = {']
    for a, b, field, v in edits:
        rec = ('record = %d' % a) if a == b else ('records = {%d, %d}' % (a, b))
        lines.append('        {%s, %s = %s},' % (rec, field, word_literal(v)))
    lines += ['    },', '}', '']
    return chr(10).join(lines)


